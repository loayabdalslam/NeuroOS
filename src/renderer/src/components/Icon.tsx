export interface IconProps extends React.SVGProps<SVGSVGElement> {
  name: string;
  size?: number;
  strokeWidth?: number;
}

export function Icon({ name, size = 16, strokeWidth = 1.75, ...rest }: IconProps): JSX.Element {
  const Component = ICONS[name] ?? CircleDot;
  return <Component size={size} strokeWidth={strokeWidth} aria-hidden {...rest} />;
}

export const hasIcon = (name: string): boolean => Boolean(ICONS[name]);

