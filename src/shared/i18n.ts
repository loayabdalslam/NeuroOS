export const DICTIONARIES: Record<string, Dict> = { en, ar, fr, es, de, zh, ja, ru, pt, it, tr, hi, ko, nl };

export const BASE_LOCALE = 'en';

export function translate(locale: string, key: string, vars?: Record<string, string | number>): string {
  const base = locale.split('-')[0];
  const dict = DICTIONARIES[base] ?? DICTIONARIES.en;
  let value = dict[key] ?? DICTIONARIES.en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) value = value.replaceAll(`{${k}}`, String(v));
  }
  return value;
}
