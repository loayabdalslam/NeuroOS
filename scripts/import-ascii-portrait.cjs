const fs = require('fs');
const path = require('path');

const sessionFile = process.argv[2] || 'script-tmp-session.jsonl';
const outFile = process.argv[3] || 'src/renderer/src/onboarding/louayArt.ts';

const lines = fs.readFileSync(sessionFile, 'utf8').split('\n');
let target = null;
for (const line of lines) {
  if (!line.includes('"type":"user/message"')) continue;
  if (!line.includes('rgb(240,241,243)') && !line.includes('rgb(240, 241, 243)')) continue;
  let obj;
  try {
    obj = JSON.parse(line);
  } catch {
    continue;
  }
  const content = obj.data?.content;
  if (!Array.isArray(content)) continue;
  const text = content
    .filter((part) => part.type === 'text')
    .map((part) => part.text)
    .join('\n');
  if (text.includes('<span') && text.includes('</span>')) target = text;
}

if (!target) {
  console.error('ASCII portrait not found in session');
  process.exit(1);
}

const start = target.indexOf('<span');
const end = target.lastIndexOf('</span>') + '</span>'.length;
let html = target.slice(start, end);
console.log('extracted html bytes:', html.length);

const decode = (value) =>
  value
    .replace(/&nbsp;/g, ' ')
    .replace(/&amp;/g, '&')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"')
    .replace(/<[^>]+>/g, '');

const rows = html.split(/<br\s*\/?>/i);
const grid = [];
let cols = 0;
for (const row of rows) {
  const cells = [];
  const re = /<span[^>]*rgb\((\d+)\s*,\s*(\d+)\s*,\s*(\d+)\)[^>]*>([\s\S]*?)<\/span>/g;
  let match;
  while ((match = re.exec(row))) {
    const char = decode(match[4]);
    if (!char) continue;
    cells.push({ char: char[0], r: Number(match[1]), g: Number(match[2]), b: Number(match[3]) });
  }
  if (cells.length) {
    cols = Math.max(cols, cells.length);
    grid.push(cells);
  }
}
console.log('rows:', grid.length, 'cols:', cols);

if (!cols || !grid.length) {
  console.error('no cells parsed');
  process.exit(1);
}

// pad to a rectangle with the plate colour
const PLATE = { r: 242, g: 243, b: 245 };
for (const row of grid) {
  while (row.length < cols) row.push({ char: ' ', ...PLATE });
}

const chars = grid.map((row) => row.map((cell) => cell.char).join(''));
const colors = Buffer.alloc(cols * grid.length * 2);
let index = 0;
for (const row of grid) {
  for (const cell of row) {
    const r = Math.round(cell.r / 17);
    const g = Math.round(cell.g / 17);
    const b = Math.round(cell.b / 17);
    const value = ((r & 0xf) << 8) | ((g & 0xf) << 4) | (b & 0xf);
    colors.writeUInt16BE(value, index * 2);
    index += 1;
  }
}

const payload = {
  cols,
  rows: grid.length,
  chars,
  colors: colors.toString('base64'),
};

const ts = `/**
 * Generated by scripts/import-ascii-portrait.cjs from the portrait supplied by
 * Louay Abdel Salam. Do not edit by hand — regenerate from the source paste.
 *
 * chars[row] is a fixed-width row of glyphs; colors packs one 12-bit RGB444
 * value per cell (big-endian uint16).
 */
export const LOUAY_ART = ${JSON.stringify(payload, null, 2)} as const;
`;
fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, ts, 'utf8');
console.log('wrote', outFile, (ts.length / 1024).toFixed(1), 'KB');
