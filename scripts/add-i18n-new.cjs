function inject(source, dictName, entries) {
  const start = source.indexOf(`const ${dictName}: Dict = {`);
  if (start < 0) throw new Error(`dictionary ${dictName} not found`);
  const end = source.indexOf('\n};', start);
  if (end < 0) throw new Error(`end of ${dictName} not found`);
  const block = Object.entries(entries)
    .map(([key, value]) => `  '${key}': ${JSON.stringify(value)},`)
    .join('\n');
  return source.slice(0, end) + '\n' + block + source.slice(end);
}

